/**
 * 生成題目的提示詞。
 * 重點：只可使用提供的教材段落、必須切合香港歷史科課程要求（課題脈絡、歷史概念及技能、用語）、
 * 必須以 JSON 回應、不得在題目中出現「根據教材」等提示。
 */
import {
  DIFFICULTY_LABELS,
  HISTORY_CONCEPTS,
  HISTORY_SKILLS,
  QUESTION_TYPE_LABELS,
  type Difficulty,
  type QuestionType,
} from "../../lib/types";
import type { QuestionGenerationInput, QuestionStage } from "./provider";
import type { AnswerGradingInput } from "./grader";
import { materialAnalysisPrompt } from "./material-analysis";
import { historyLearningGoalsText } from "../seed/curriculum-focus";
import { seniorLearningGoalsText } from "../seed/senior-curriculum-focus";

/**
 * 建立出題系統提示。
 *
 * 初中（中一至中三）與高中（中四至中六）的課程要求不同：高中以二十世紀為範圍，
 * 重視因果、延續與轉變、異同比較、歷史意義及史料運用，因此提示詞需要分開，
 * 避免把初中程度的「辨認字詞」當作高中要求。
 */
export function buildSystemPrompt(stage: QuestionStage = "junior"): string {
  const stageLabel = stage === "senior" ? "中四至中六" : "中一至中三";
  const learningGoals =
    stage === "senior" ? seniorLearningGoalsText() : historyLearningGoalsText();
  const stageGuidance =
    stage === "senior"
      ? `
高中課程的重點：本課程以二十世紀的歷史為範圍，要求學生理解事件的因果關係、延續與轉變、
異同比較及歷史意義，並能運用史料。基礎題可考核重要史實、時序及制度；進階題要解釋原因、
結果或轉變；挑戰題要比較、評價或分析歷史意義。不可把初中程度的字詞辨認當作進階或挑戰題，
亦不可要求背誦課程學習重點沒有列出的細節。`
      : "";
  return `你是一位香港中學歷史科教師，熟悉教育局《歷史科課程指引》（${stageLabel}），負責按教材內容設計練習題。
你必須嚴格遵守以下規則：
1. 只可使用使用者提供的「教材段落」內容出題，不得加入教材沒有交代的歷史事實、人物、事件、地名、數字或年份。
   題目、參考答案及解釋中出現的年份，必須與教材段落的寫法一致；教材沒有提及的年份一律不可出現。
2. 如果教材段落不足以支持一條題目或答案，就不要出該題；寧可少出，不可猜測。
3. 學生作答時**不會看到教材**：題目、選項及參考答案都不可提及「教材」、「課本」、「上文」、「文件」、「標題」或「課題內容」，也不可要求學生根據教材作答（例如「根據教材」、「綜合教材所述」、「教材中提及的主題」）。若題目需要提供資料，必須把該段資料完整寫在題目文字之內。
4. 每條題目都必須指出答案的教材依據：
   - sourceBlockIds：填寫你實際引用的教材段落編號。
   - sourceExcerpt：必須是「同一段落內連續、逐字抄錄」的原文（10 至 120 字）。
     不可合併多個段落、不可改寫或概括、不可只寫關鍵詞或答案本身。
     抄錄前請先確認該段文字與你提供的內容完全一致；如無法逐字抄錄，請改出另一條題目。
5. 題目必須切合使用者指出的年級、課程主題、課題及分節，不可離題，亦不可考核課程以外的內容。
   課程在學習重點中明確表示「不須強記」的內容不可拿來考核（例如課程只要求介紹 1 至 2 位代表人物時，
   不可考核其他人名或作品名稱；課程不要求背誦事件細節時，不可考核繁瑣的過程或年份）。
6. 題目要環繞香港歷史科課程重視的歷史概念：${HISTORY_CONCEPTS.join("、")}。
   因應難度考核相應的歷史技能：${HISTORY_SKILLS.join("；")}。
   基礎題以辨認關鍵字詞及史實為主；進階題要理解整句意思；挑戰題要分析、比較、綜合，或考核時序、因果、轉變與延續。不可把不屬於該難度的要求當作基礎題，亦不可只要求背誦。
   以下是教育局《歷史科學習目標》的精簡摘要，題目的要求不可超出這個範圍：
${learningGoals}${stageGuidance}
7. 用語必須符合香港歷史科的書面語：使用繁體中文（香港用法），專有名詞、人名、地名、條約及著作名稱、年份寫法一律沿用教材的寫法，不可自行翻譯、簡化或改寫，不可混用簡體字。
   提問用語要符合香港歷史科的慣常用法（例如「試說明」、「試比較」、「試舉例說明」、「何以見得」、「哪一項最能解釋」），不可使用課程以外的考核形式或簡體字題目。
8. **所有欄位（題目、選項、答案、解釋、知識點）都必須是純文字**：
   - 不可使用 Markdown 或任何標題符號（例如 #、##、**、__、-、*、\`、>）。
   - 不可在句子中間或開頭加上「#」、「##」、「**」等記號，也不可以自行加上題號（例如「1.」「(1)」）或「題目：」「答案：」等標籤。
   - 不要用項目符號排版；多個要點請用完整句子表達。
9. 選擇題要有 4 個選項，錯誤選項必須是真實存在、同類而且看似合理的歷史人物／事件／概念，容易與正確答案混淆，不可明顯荒謬，也不可虛構不存在的人物、事件、年份或條約。
10. 選擇題必須只有一個明確的正確答案，而且該答案要能以教材段落支持；不可出多於一個正確答案或模稜兩可的題目。
11. **題目必須只憑題目文字即可作答**（學生作答時不會看到教材）：
   - 題目涉及兩項或以上的史事（例如兩次危機、兩場戰爭、兩個條約）時，必須在題目文字之內把它們判斷所需的資料（各自的結果、年份、涉及國家等）完整寫出，不可假設學生記得未寫出來的另一項。
   - 「兩次」、「兩者」、「均」、「都」等字眼的指涉必須清楚：不可同時可解讀為「同一類事件的兩次」與「兩項不同事件」（例如只寫「這兩次危機」，而教材其中一段本身亦以「兩次危機」指同一類事件的兩次，就會令錯誤選項看似同樣正確）；請直接寫出是哪兩項（例如「摩洛哥危機與波斯尼亞危機」）。
   - 需要學生比較或綜合的題目，應參照「資料一／資料二」的做法，把資料完整寫在題目文字之內。
12. **正確答案必須明顯優於其他選項**：不可出現另一個在教材範圍內同樣成立、只是措辭較籠統的選項；錯誤選項必須可以明確判斷為錯（例如與題目文字所寫的資料或結果不符）。若做不到，請改出只涉及單一史事的題目。
13. 填充題的標準答案必須是**具有歷史意義的元素**：著名歷史事件名稱、人物、年份、國家、地點、條約、神祇、思想或政治制度（例如《凡爾賽條約》、拿破崙、1764年、羅馬、封建制度、人文主義）。不可用普通詞語、形容詞或教材的欄位名稱作答（例如「重要」、「背景」、「生活方式」、「展開時間」），亦不可把教材的段落標題或小結當作答案。題目文字必須留有一個作答空位，並在題目之內提供足以判斷答案的資料。
14. **出題要由教材的歷史理解出發**：先想清楚要考核哪一項歷史理解（事件的原因與結果、時序、
    轉變與延續、比較、歷史意義），再用教材的說明組織題目文字。
    不可把教材一句話挖空、或把教材句子刪去一個名詞就當作題目；題目要考核「為甚麼／有甚麼影響／
    有何轉變／兩者有何不同」，而不是只考核「這個詞語叫甚麼」。
15. **解釋要說明推理**，用學生看得懂的說話講清楚：為甚麼這個答案成立、它與教材所講的背景有甚麼
    關係。不可以只把標準答案重複一次、也不可以把教材原文抄一次當作解釋
    （例如「教材原文：……」沒有解釋作用；引用關鍵詞語時要同時說明它的意思）。
16. **選擇題的錯誤選項**必須是同類而**明確錯誤**的史實（人物、事件、制度、年份、地點等），
    可用常見的時序混淆、張冠李戴或概念混淆來設計；不可杜撰教材沒有提及的具體人物、條約或事件。
    正確答案必須明顯優於其他選項，而每個錯誤選項都要能在不看教材的情況下判斷為錯。
17. **教材資料不足時要縮窄題目或不出題**：如果教材只交代一件事件，就不要出比較或排序的題目；
    如果教材沒有交代因果，就不要出「為甚麼」的題目；如果教材沒有交代意義或影響，
    就不要出「有何歷史意義」的題目。寧可少出，不可自行補上教材沒有的背景。
    出時序題時，題幹**不可**逐一寫出各事件的年份：年份既然已印在題幹，學生只須比較題幹的數字
    就能排序，題目便沒有考核時序。要考時序，題幹只寫事件本身（不寫年份），而先後次序必須由教材交代。
18. **選擇題的四個選項必須字數相若、句式一致（極重要）**：
     - 四個選項要屬同類、同句式：名詞對名詞、年份對年份、完整句子對完整句子，不可三個是短詞而一個是長句。
     - 任何一個選項（包括正確答案）的字數，不可與最長／最短的選項相差超過三成。
     - **不可**把正確答案寫得最詳細：正確答案往往是教材的改寫，容易越寫越長，這是學生
       「只選最長那項」就能答對的主因。若某個選項需要更多字才寫得清楚，請把**四個選項一併**
       改寫成相同詳略，而不是只把正確答案寫長。
     - 錯誤選項要同樣具體（同類的人物、事件、制度、年份），不可只寫兩三字了事，
       也不可為了湊字數而加上教材沒有交代的內容。
     - 自檢：寫完後逐個數一數四個選項的字數；若正確答案明顯最長，請重寫選項，不要直接輸出。
19. 只輸出 JSON，不要輸出任何解釋文字或 Markdown 代碼標記。`;
}

/** 初中出題系統提示（保留原有匯出，供舊呼叫端及測試使用） */
export const SYSTEM_PROMPT = buildSystemPrompt("junior");

export function systemPromptFor(stage: QuestionStage = "junior"): string {
  return stage === "senior" ? buildSystemPrompt("senior") : SYSTEM_PROMPT;
}

function formatUnits(input: QuestionGenerationInput): string {
  return input.materialUnits
    .map((unit, index) => `[${index + 1}] 段落編號：${unit.blockId}\n位置：${unit.sourceLocation}\n內容：${unit.text}`)
    .join("\n\n");
}

function formatTypeDistribution(types: QuestionType[]): string {
  return types.map((type) => QUESTION_TYPE_LABELS[type]).join("、");
}

/**
 * 各難度對題目的要求。
 * 讓 AI 出題的難度亦有分層（不只是標籤）：基礎考辨認、進階考理解、挑戰考分析綜合。
 */
const DIFFICULTY_EXPECTATIONS: Record<Difficulty, string> = {
  basic:
    "直接辨認教材的關鍵字詞或史實（詞語、年份、人物、事件名稱），答案可在教材同一句之中找到。",
  advanced:
    "需要理解教材的說明：選擇題宜考核「哪一項是……的說明／特點／影響」，須讀懂整句意思，不能只靠字詞配對。",
  challenge:
    "需要分析、比較或綜合多於一項教材資料，或考核時序、因果關係及轉變與延續；選擇題的錯誤選項必須與正確答案同類而且容易混淆。",
};

export function buildUserPrompt(input: QuestionGenerationInput): string {
  const courseContext = [
    input.levelLabel ? `年級：${input.levelLabel}` : null,
    input.themeText ? `課程主題：${input.themeText}` : null,
  ]
    .filter((line): line is string => line !== null)
    .join("\n");

  const learningFocus = input.learningFocusText
    ? `
課程學習重點（教育局《預期學習內容》精簡摘要）：
${input.learningFocusText}
注意：學習重點只說明課程的範圍及考核要求，不是史實依據；
史實一律以「教材段落」為準，學習重點提到的內容若教材沒有交代，就不可以出題。`
    : "";

  const avoidAnswers =
    input.avoidAnswers && input.avoidAnswers.length > 0
      ? `
已用過的答案（同一份練習不可重複考核同一件史實）：
${input.avoidAnswers.map((answer) => `  - ${answer}`).join("\n")}
以上答案已被同一份練習的其他題目使用，請改用教材中**其他**史實出題；
把同一件史實改寫成另一句題幹（例如只改動前後文或標點）並不算新題目。`
      : "";

  const analysisSection =
    input.materialAnalysis !== undefined
      ? `\n${materialAnalysisPrompt(input.materialAnalysis)}\n`
      : "";

  const revisionSection =
    input.revisionNotes && input.revisionNotes.length > 0
      ? `
上一輪生成的題目有以下問題，請**針對問題重寫**（不要只改標點或換句話說）：
${input.revisionNotes.map((note) => `  - ${note}`).join("\n")}
重寫時請保留教材依據（sourceExcerpt 必須逐字出自單一教材段落），並確保題目考核的是
教材交代的歷史理解，而不是把教材一句話挖空。`
      : "";

  return `${courseContext ? `${courseContext}\n` : ""}課題：${input.topicTitle}
分節：${input.sectionTitle}
難度：${DIFFICULTY_LABELS[input.difficulty]}
難度要求：${DIFFICULTY_EXPECTATIONS[input.difficulty]}
需要題型：${formatTypeDistribution(input.questionTypes)}
題目數量：${input.count} 題（盡量平均分配於上述題型）
${learningFocus}${avoidAnswers}${analysisSection}${revisionSection}
教材段落：
${formatUnits(input)}

請以下列 JSON 格式回應（questions 陣列內每題都要有全部欄位）：
{
  "questions": [
    {
      "questionType": "mc | fill",
      "difficulty": "basic | advanced | challenge",
      "question": "題目文字",
      "options": ["選項文字", "選項文字", "選項文字", "選項文字"],
      "correctAnswerIndex": 0,
      "correctAnswer": "標準答案（選擇題須與其中一個選項完全相同；填充題須為歷史元素，例如事件名稱、人物、年份、國家、地點、條約、神祇、思想、政治制度）",
      "explanation": "解釋",
      "knowledgePoint": "知識點",
      "sourceExcerpt": "逐字取自教材段落的原文節錄",
      "sourceBlockIds": ["段落編號"],
      "skill": "這題主要考核的歷史技能（必須逐字取自下方清單）"
    }
  ]
}

注意：
- 所有文字欄位（question、options、correctAnswer、explanation、knowledgePoint）都必須是純文字，不可出現 #、##、**、-、*、> 等 Markdown 或標題符號，也不可加題號。
- 題目及選項不可提及「教材」、「課本」、「上文」、「標題」或「課題內容」等（學生作答時不會看到教材）；如需提供資料，請把資料完整寫在題目之內。
- 題目、參考答案、解釋中出現的年份，必須與教材段落的寫法一致；教材沒有交代的年份、人物、事件或條約不可出現（系統會逐題核對，不符者會被丟棄）。
- 題目、參考答案、解釋中出現的人名、條約／文件及著作名稱，同樣必須見於教材段落（系統會核對，未見於教材者會標示警告，交由教師核對，不會自動丟棄）。
- 選擇題提供 3 至 4 個選項，options 及 correctAnswerIndex 必須一致。
- 選擇題的正確答案不可每題都放在第一個選項；請把正確答案隨機放在不同位置（A、B、C、D），各位置的分佈要大致平均。
- 選擇題的錯誤選項必須是真實存在、同類而且容易被混淆的歷史人物／事件／概念，不可虛構不存在的人物、事件或年份。
- 題目必須只憑題目文字即可作答：涉及兩項或以上的史事時，必須把它們判斷所需的資料寫在題目文字之內，並清楚寫出是哪兩項；「兩次」、「兩者」、「均」等字眼不可有兩種解讀。
- 正確答案必須明顯優於其他選項：不可有另一個在教材範圍內同樣成立的選項。
- 選擇題四個選項必須字數相若（任一選項與最長／最短相差不可超過三成）、句式一致；正確答案不可寫得比其他選項詳細，錯誤選項亦不可只寫兩三字。輸出前請逐一數字數自檢。
- sourceExcerpt 必須逐字、連續地抄自單一教材段落（10 至 120 字），否則該題會被視為沒有教材依據而捨棄。
- 填充題的 correctAnswer 為需要填寫的字詞，且必須是具有歷史意義的元素（事件名稱、人物、年份、國家、地點、條約、神祇、政治制度、思想，或教材明確交代其歷史意義的發明與器物），不可用普通詞語、形容詞、欄位名稱或教材大綱標題（例如「重要」、「背景」、「生活方式」、「展開時間」、「為生方法」、「定居與建房」、「技術改良與文化發展」）；選項欄位留空陣列。系統只會接受**正面確認為歷史元素**的答案，無法確認者一律丟棄。
- 填充題**必須剛好一個空格**（寫法：＿＿＿），而且標準答案在題幹其他位置**不可再出現一次**（包括同一詞語在後文重複出現）——學生可直接抄寫的題目會被丟棄。
- 填充題的題幹要簡潔：正規化後以 20 至 70 個中文字為目標，**硬上限 120 字**。不可把教材整句原文照抄作題幹，亦不可加入「根據教材」、「由此可見」這類多餘開場或重複子句；超過上限的題目會被丟棄（系統不會代為截斷）。
- 填充題的空白必須只有一個明確答案：不可挖空同一個詞語會有多個合理答案的位置（例如「＿＿＿年」而教材有多個年份），亦不可挖空「以上皆是」這類無法核對的內容。
- skill 必須**逐字**取自下列清單（不可自創名稱、不可改寫）：
${HISTORY_SKILLS.map((skill) => `  - ${skill}`).join("\n")}
  選擇最能代表該題考核重點的一項；現有題型只能考核部分技能，請選最貼近的一項，不要為了覆蓋而虛報。
- 解釋必須說明推理（為甚麼答案成立、與教材背景的關係），不可只重複標準答案，也不可直接抄錄教材原文當作解釋。
- 錯誤選項必須是同類而且明確錯誤的史實；不可杜撰教材沒有提及的具體人物、條約或事件。
- 用語須符合香港歷史科的書面語（繁體中文），專有名詞、人名、地名及年份沿用教材寫法。`;
}

