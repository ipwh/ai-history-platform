/**
 * 課題級「人物／事件卡」的**內建**內容（M2，最小版）。
 *
 * ── 用途 ──────────────────────────────────────────────────────────────
 * 澄清候選與練習開場的建議問題，預設由課程索引（課題／分節標題及關鍵詞）即時產生，
 * 質素參差。課題卡讓科組為指定課題事先寫好**貼近學生實際困惑**的提問與混淆點，
 * 並優先顯示在澄清／開場建議中。
 *
 * ── 安全邊界 ──────────────────────────────────────────────────────────
 * 卡片內容會直接顯示給學生，因此**只可**包含引導性問題及概念提示：
 *   - **不可**寫入標準答案、選項字母對錯、解釋、評分參考或任何評卷準則；
 *   - **不可**寫入未發布題目的題幹；
 *   - 只描述「應該思考的方向」，不描述「正確結論」。
 * 讀取時不會查詢題庫，因此即使在卡片檔寫錯，亦不會把題目內容帶進來；
 * 測試（tests/tutor-topic-cards.test.ts）另會檢查內建卡片不含敏感字樣。
 *
 * ── 為何同時支援 `data/tutor-topic-cards/*.json` ──────────────────────
 * 科組需要在不改程式碼的情況下更新卡片（見 services/tutor-topic-cards.ts）。
 * 內建版本是「開箱即用」的起點，`data/` 版本可覆蓋同 ID 的課題；該目錄不在版本
 * 控制內（`/data` 已列入 .gitignore），適合放校內調校後的版本。
 */
export interface TutorTopicCard {
  topicId: string;
  title: string;
  /** 建議提問：必須是「思考方向」，不是答案 */
  suggestedQuestions: string[];
  /** 常見混淆點：只描述易混淆之處，不給結論 */
  confusionPoints: string[];
}

