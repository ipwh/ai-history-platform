/**
 * 產生單一課題的「學習重點（精簡摘要）」文字，供提示詞使用。
 * 沒有對應課題（例如教師參考資料）時回傳空字串，避免在提示詞留下空標籤。
 */
export function topicLearningFocusText(topicNumber: number | null | undefined): string {
  if (typeof topicNumber !== "number") return "";
  const focus = TOPIC_LEARNING_FOCUS[topicNumber];
  if (!focus) return "";
  const strands = focus.strands
    .map(
      (strand) =>
        `- ${strand.title}：${strand.points.join("；")}。課程著重：${strand.emphasis}。`,
    )
    .join("\n");
  return `課題${topicNumber}「${focus.title}」的學習重點（共 ${focus.lessons} 節；有「延伸部分」的項目屬選修）：\n${strands}`;
}
