import { HISTORY_SKILLS } from "../../lib/types";

/** 學習重點中的一個分題（對應《預期學習內容》的欄目） */
export interface TopicFocusStrand {
  /** 分題名稱 */
  title: string;
  /** 學習重點（精簡摘要） */
  points: string[];
  /** 課程明確著重的方向（例如「避免學生強記人名及作品名稱」） */
  emphasis: string;
}

export interface TopicLearningFocus {
  /** 課題名稱（與 src/server/seed/curriculum.ts 的課題名稱一致） */
  title: string;
  /** 建議節數（按《預期學習內容》） */
  lessons: number;
  strands: TopicFocusStrand[];
}

/**
 * 學習目標（《歷史科學習目標》精簡版）。
 * 技能一項與 src/lib/types.ts 的 HISTORY_SKILLS 相同，避免出現兩種寫法。
 */
export const HISTORY_LEARNING_GOALS = {
  knowledge: [
    "從不同的角度（政治、經濟、科技、社會、宗教、藝術等）認識和理解世界各文化在不同時期的主要特徵",
    "認識和理解香港發展的主要特徵，以及這些特徵與國家和世界歷史發展的關係",
    "掌握研習歷史的基本概念和辭彙",
    "理解歷史事件的因果關係",
    "掌握主要歷史事件的發展、轉變及延續，明白可以從不同的角度和觀點解釋歷史",
  ],
  skills: HISTORY_SKILLS,
  attitudes: [
    "提高對過去的人和事的興趣及欣賞人類的成就和理想",
    "掌握歷史研習與現今生活的密切關係",
    "認識不同社會及不同時代所持的觀點、信念和價值觀，從而建立正面的價值觀和態度",
    "願意為古物古蹟的保護、文化傳承的保育，以及歷史文化的推廣盡一己之力",
  ],
} as const;

/** 供提示詞使用的學習目標文字（精簡摘要） */
export function historyLearningGoalsText(): string {
  return [
    `知識和理解：${HISTORY_LEARNING_GOALS.knowledge.join("；")}。`,
    `技能：${HISTORY_LEARNING_GOALS.skills.join("；")}。`,
    `態度和價值觀：${HISTORY_LEARNING_GOALS.attitudes.join("；")}。`,
  ].join("\n");
}

