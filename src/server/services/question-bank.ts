/**
 * 題庫批次生成。
 *
 * 為每個課程課題的分節生成練習題目（使用設定的 LLM provider，預設為本地示範生成）。
 * 生成結果會經過 schema 驗證及教材依據核對；沒有依據的題目不會儲存。
 *
 * 難度分配：每個分節的目標題數會平均分配到基礎／進階／挑戰三個難度，
 * 令學生選擇任何難度時都有題庫題目可用（本地示範生成亦會按難度採用不同出題規則）。
 *
 * 發布策略（Sprint 7.8）：
 *   - 通過**自動品質驗證**的題目（任何 provider）在生成時即記錄驗證結果，並在
 *     `AUTO_PUBLISH_VALIDATED_QUESTIONS=true`（預設）時立即發布——學生自學不應等待
 *     教師逐題預先批准。正式環境同樣適用，因此批次生成可直接供學生使用。
 *   - 未通過自動驗證的題目只會是草稿，由教師覆核、修正或重新驗證。
 *   - 示範模式（`DEMO_AUTO_PUBLISH_QUESTIONS=true`，僅限非正式環境）仍會額外發布
 *     本地示範生成的題目，令沒有教師在場時仍可試用。
 */
import { DIFFICULTY_LABELS, type Difficulty } from "../../lib/types";
import { getServerConfig, isProductionRuntime } from "../config";
import { describeLlm } from "../llm";
import { countQuestions, getQuestion, listQuestions } from "../repositories/questions";
import { listSections, listTopics } from "../repositories/topics";
import {
  autoValidationIsCurrent,
  publishAutoGeneratedQuestion,
  generateQuestions,
} from "./question-service";

/** 題庫要齊備的難度（學生在練習設定可選的三個難度） */
const BANK_DIFFICULTIES: Difficulty[] = ["basic", "advanced", "challenge"];

export interface QuestionBankOptions {
  /** 只處理指定課題 */
  topicId?: string | null;
  /** 每個分節的目標題數（會平均分配到基礎／進階／挑戰三個難度） */
  perSection?: number;
  /** 只建立草稿，不自動發布 */
  draftOnly?: boolean;
  /** 進度回報 */
  onTopic?: (message: string) => void;
}

export interface QuestionBankReport {
  topicsProcessed: number;
  created: number;
  published: number;
  /**
   * 這次新增且**通過自動品質驗證**的題目數（任何環境都會記錄）。
   * 這些題目在 `AUTO_PUBLISH_VALIDATED_QUESTIONS=true`（預設）時立即供學生練習。
   */
  autoPublishedValidated: number;
  /** 保留為草稿等待教師確認的題目數（品質閘門未確定，Sprint 7.9） */
  heldForTeacher: number;
  /** 其中已確實發布（學生即刻可用）的題目數 */
  publishedValidated: number;
  autoPublish: boolean;
  /**
   * 本應套用示範自動發布但被 fail-closed 停用的原因（例如正式環境），未停用時為 null。
   * 呼叫端應把原因顯示給操作者，避免誤以為題目已發布。
   */
  autoPublishSuppressedReason: string | null;
  /** 這次新增的題目按難度分佈 */
  createdByDifficulty: Record<Difficulty, number>;
  duplicateSections: string[];
  insufficientSections: string[];
  totalsByTopic: { topicId: string; title: string; count: number }[];
}

/**
 * 把每個分節的目標題數平均分配到三個難度。
 * 例如 perSection = 5 → 基礎 2 題、進階 2 題、挑戰 1 題；
 * perSection = 3 → 基礎／進階／挑戰各 1 題。
 */
export function allocateByDifficulty(total: number): Map<Difficulty, number> {
  const allocation = new Map<Difficulty, number>();
  const base = Math.floor(total / BANK_DIFFICULTIES.length);
  const remainder = total % BANK_DIFFICULTIES.length;
  BANK_DIFFICULTIES.forEach((difficulty, index) => {
    const count = base + (index < remainder ? 1 : 0);
    if (count > 0) allocation.set(difficulty, count);
  });
  return allocation;
}

export async function generateQuestionBank(
  options: QuestionBankOptions = {},
): Promise<QuestionBankReport> {
  const config = getServerConfig();
  const perSection = options.perSection ?? 5;
  const llm = describeLlm();
  const autoPublishRequested =
    !options.draftOnly && config.autoPublishMockQuestions && llm.provider === "mock";
  // 示範自動發布仍只限非正式環境（未經任何驗證的示範題目不應寫入正式題庫）。
  // 通過自動品質驗證的題目則不受此限，見 recordAutoValidationAndPublish。
  const autoPublish = autoPublishRequested && !isProductionRuntime();
  const autoPublishSuppressedReason =
    autoPublishRequested && !autoPublish
      ? "偵測到正式環境（Cloud Run 或 NODE_ENV=production）：不套用示範自動發布；已通過自動品質驗證的題目仍會立即供學生練習。"
      : null;
  if (autoPublishSuppressedReason) options.onTopic?.(autoPublishSuppressedReason);

  const topics = listTopics().filter(
    (topic) => topic.level !== 0 && (!options.topicId || topic.id === options.topicId),
  );

  let created = 0;
  let published = 0;
  let autoPublishedValidated = 0;
  let publishedValidated = 0;
  // 品質閘門未確定、保留為草稿等待教師確認的題目（Sprint 7.9）
  let heldForTeacher = 0;
  const createdByDifficulty: Record<Difficulty, number> = {
    basic: 0,
    advanced: 0,
    challenge: 0,
  };
  const duplicateSections = new Set<string>();
  const insufficientSections = new Set<string>();

  for (const topic of topics) {
    const childSections = listSections(topic.id).filter((section) => section.parentId !== null);
    const targets = childSections.length > 0 ? childSections : listSections(topic.id);

    for (const section of targets) {
      // 逐個難度補足目標題數，確保題庫同時有基礎、進階及挑戰的題目
      for (const [difficulty, target] of allocateByDifficulty(perSection)) {
        const existing = listQuestions({
          topicId: topic.id,
          sectionIds: [section.id],
          difficulties: [difficulty],
        }).length;
        if (existing >= target) continue;

        let generated: Awaited<ReturnType<typeof generateQuestions>>;
        try {
          generated = await generateQuestions({
            topicId: topic.id,
            sectionIds: [section.id],
            questionTypes: ["mc", "fill"],
            difficulty,
            questionCount: target - existing,
          });
        } catch (error) {
          const message = error instanceof Error ? error.message : String(error);
          const label = `${topic.title} › ${section.title}`;
          if (message.includes("重複")) duplicateSections.add(label);
          else insufficientSections.add(label);
          continue;
        }

        created += generated.questions.length;
        createdByDifficulty[difficulty] += generated.questions.length;
        for (const question of generated.questions) {
          // Sprint 7.9：品質閘門未確定的題目只保留為草稿等待教師確認，
          // 不屬於「自動發布」流程（亦不應令整批失敗）。
          if (question.teacherConfirmationRequired) {
            heldForTeacher += 1;
            continue;
          }
          if (autoPublish) {
            // 示範／首次建立流程：自動發布但不留下覆核紀錄（教師端會標示為未經人工覆核）。
            // 發布被拒時不吞掉錯誤，讓批次腳本如實失敗，而不是回報已發布。
            publishAutoGeneratedQuestion(question.id);
            published += 1;
          }
          // 生成階段已通過自動品質驗證（見 question-service.recordAutoValidationAndPublish）：
          // 這些題目在任何環境都立即供學生自學，因此與示範自動發布分開計數。
          const current = getQuestion(question.id);
          if (current && autoValidationIsCurrent(current)) {
            autoPublishedValidated += 1;
            if (current.status === "published") publishedValidated += 1;
          }
        }
      }
    }

    const counts = BANK_DIFFICULTIES.map(
      (difficulty) =>
        `${DIFFICULTY_LABELS[difficulty]} ${countQuestions({ topicId: topic.id, difficulties: [difficulty] })}`,
    ).join("、");
    options.onTopic?.(
      `${topic.title}：合計 ${countQuestions({ topicId: topic.id })} 題（分節 ${targets.length} 個；${counts}）`,
    );
  }

  return {
    topicsProcessed: topics.length,
    created,
    published,
    autoPublishedValidated,
    publishedValidated,
    heldForTeacher,
    autoPublish,
    autoPublishSuppressedReason,
    createdByDifficulty,
    duplicateSections: [...duplicateSections],
    insufficientSections: [...insufficientSections],
    totalsByTopic: topics.map((topic) => ({
      topicId: topic.id,
      title: topic.title,
      count: countQuestions({ topicId: topic.id }),
    })),
  };
}
