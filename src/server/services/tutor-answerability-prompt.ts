/** 學伴可答性狀態的提示詞區塊（與判斷邏輯分開，避免模組循環依賴）。 */
import type { TutorAnswerabilityDecision } from "./tutor-answerability";

/**
 * 提示詞中的作答政策區塊。
 *
 * A 狀態由既有【教材片段】規則處理，因此回傳 `null`，避免重複指示；
 * D 狀態不會到達模型（路線會先澄清）。
 */
export function describeTutorAnswerabilityForPrompt(
  decision: TutorAnswerabilityDecision,
): string | null {
  switch (decision.state) {
    case "A-material-supported":
      return null;
    case "B-partial-material-support": {
      const lines = [
        "【作答狀態：B 教材只部分支持】本題部分內容可由校本教材片段支持，部分沒有。",
        "1. 先直接回答教材片段支持的面向，並只以片段內容陳述史實。",
        "2. 明確指出哪些面向教材片段找不到（說「找不到」，不可說教材沒有），並說明這限制了哪些結論。",
        "3. 之後才可補充一般歷史知識，並標明「以下屬一般歷史知識」。",
        "4. 不可用片段以外的細節假裝成教材說法。",
      ];
      if (decision.evidenceSupport === "inferential") {
        lines.push(
          "5. 本次片段只提供背景／關鍵詞，**沒有直接交代提問所問的關係**（因果、比較或評價）：要把這部分寫成「片段未有直接說明，以下是根據一般歷史知識的推論」，不可當成教材結論。",
        );
      }
      return lines.join("\n");
    }
    case "C-general-knowledge": {
      const confidence = decision.confidence ?? "C1-reliable";
      const common = [
        "1. **必須作答**：不可以因為找不到教材而拒絕回答，亦不可只回覆「請重新選擇課題」或以澄清代替回答。",
        "2. 開首一句說明「校本教材找不到這部分的內容」，語氣要簡短、自然，不要道歉式長篇解釋。",
        "4. 不可虛構教材段落、引文、頁數、出處或評分標準；不可聲稱這是教材的說法。",
      ];
      if (confidence === "C3-no-reliable-basis") {
        return [
          "【作答狀態：C3 校本教材未涵蓋，而且不能可靠核實】本次檢索沒有可用片段，提問要求的細節（例如逐字引文、精確日期或數字）無法可靠核實。",
          common[0],
          common[1],
          "3. 先說明可以確認的背景（並標明「以下屬一般歷史知識」），再明確指出哪一部分無法核實、為甚麼，以及需要甚麼證據（例如原始文件、條約原文、官方紀錄）。",
          "4. 不可虛構教材段落、引文、頁數、出處或評分標準；不可聲稱這是教材的說法；亦不可用「大約」「據說」假裝有來源。",
          "5. 最後可建議學生查閱哪一類可靠來源（教材相關章節、原始文件），並提醒以老師及教材為準。",
          "6. 仍需遵守回覆結構、深度及禁代做功課的規則。",
        ].join("\n");
      }
      if (confidence === "C2-partial-or-disputed") {
        return [
          "【作答狀態：C2 校本教材未涵蓋，而且只有部分可靠知識或存在爭議】本次檢索沒有可用片段。",
          common[0],
          common[1],
          "3. 以一般歷史知識回答可靠的部分，並標明「以下屬一般歷史知識」。",
          "4. 明確區分：哪部分屬史學界普遍接受、哪部分仍有爭議，或自己不能確定；不可把爭議寫成定論。",
          "5. 不可虛構教材段落、引文、頁數、出處或評分標準；不可聲稱這是教材的說法。",
          "6. 可指出學生可如何自行核實（教材相關章節、原始文件），並提醒以老師及教材為準。",
          "7. 仍需遵守回覆結構、深度及禁代做功課的規則。",
        ].join("\n");
      }
      return [
        "【作答狀態：C1 校本教材未涵蓋，但屬可靠的一般歷史知識】本次檢索沒有找到可用的校本教材片段。",
        common[0],
        common[1],
        "3. 之後以可靠的一般歷史知識，按學生程度直接、清楚地回答；第一次引用教材以外的內容時標明「以下屬一般歷史知識」。",
        "4. 不可虛構教材段落、引文、頁數、出處或評分標準；不可聲稱這是教材的說法。",
        "5. 對有爭議的詮釋或自己不能確定的細節，要說明屬推論或不確定，並建議以老師及教材為準。",
        "6. 仍需遵守回覆結構、深度及禁代做功課的規則。",
      ].join("\n");
    }
    case "D-needs-clarification":
    case "out-of-scope":
      return null;
  }
}
