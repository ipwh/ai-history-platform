/**
 * 自動發布邊界測試（Sprint 6，P1）。
 *
 * 背景：`DEMO_AUTO_PUBLISH_QUESTIONS=true` 會令示範模式的批次生成把題目直接發布，
 * 但那些題目**未經教師覆核**。若環境變數被複製到正式環境，批次腳本便可把未覆核題目
 * 寫入正式題庫——這是必須擋住的邊界。
 *
 * 驗證：
 *   1. 正式環境（Cloud Run `K_SERVICE` 或 `NODE_ENV=production`）一律拒絕自動發布，
 *      即使 `DEMO_AUTO_PUBLISH_QUESTIONS=true` 亦然。
 *   2. 示範自動發布關閉時亦拒絕。
 *   3. 批次生成在正式環境只建立草稿，並回報停用原因（不會靜默假裝已發布）。
 *   4. 本機示範模式仍可自動發布，但題目不會有覆核紀錄（教師端標示為未經人工覆核）。
 */
import { afterEach, beforeAll, beforeEach, describe, expect, it } from "vitest";
import { freshTestDatabasePath } from "./test-database";

process.env.APP_DATABASE_PATH = freshTestDatabasePath("auto-publish");
process.env.LLM_PROVIDER = "mock";
process.env.AUTH_SECRET = "test-secret-0123456789abcdefghijklmnop";
delete process.env.ADMIN_TOKEN;

type Config = typeof import("@/server/config");
type QuestionBankService = typeof import("@/server/services/question-bank");
type QuestionRepository = typeof import("@/server/repositories/questions");
type QuestionService = typeof import("@/server/services/question-service");
type Seed = typeof import("@/server/seed");
type Types = typeof import("@/lib/types");

let config: Config;
let bank: QuestionBankService;
let questionsRepo: QuestionRepository;
let questionService: QuestionService;
let seed: Seed;
let types: Types;

const ORIGINAL_NODE_ENV = process.env.NODE_ENV;
const ORIGINAL_K_SERVICE = process.env.K_SERVICE;
const ORIGINAL_AUTO_PUBLISH = process.env.DEMO_AUTO_PUBLISH_QUESTIONS;

/** NODE_ENV 在型別上是唯讀，測試需要模擬正式環境，因此以可寫入的檢視存取 */
const env = process.env as Record<string, string | undefined>;

beforeAll(async () => {
  config = await import("@/server/config");
  bank = await import("@/server/services/question-bank");
  questionsRepo = await import("@/server/repositories/questions");
  questionService = await import("@/server/services/question-service");
  seed = await import("@/server/seed");
  types = await import("@/lib/types");
  seed.ensureBootstrap();
});

beforeEach(() => {
  env.NODE_ENV = "test";
  delete process.env.K_SERVICE;
  process.env.DEMO_AUTO_PUBLISH_QUESTIONS = "true";
});

afterEach(() => {
  if (ORIGINAL_NODE_ENV === undefined) delete env.NODE_ENV;
  else env.NODE_ENV = ORIGINAL_NODE_ENV;
  if (ORIGINAL_K_SERVICE === undefined) delete process.env.K_SERVICE;
  else process.env.K_SERVICE = ORIGINAL_K_SERVICE;
  if (ORIGINAL_AUTO_PUBLISH === undefined) delete process.env.DEMO_AUTO_PUBLISH_QUESTIONS;
  else process.env.DEMO_AUTO_PUBLISH_QUESTIONS = ORIGINAL_AUTO_PUBLISH;
});

let sequence = 0;

/** 插入一條草稿題目（模擬批次生成剛建立的題目） */
function insertDraft(): string {
  sequence += 1;
  const question = types.questionSchema.parse({
    id: `auto-publish-${sequence}`,
    topicId: "topic-5",
    sectionId: "topic-5-renaissance-features",
    questionType: "mc",
    difficulty: "basic",
    question: `自動發布邊界測試題目 ${sequence}`,
    options: ["人文主義", "重商主義", "軍國主義", "自然主義"],
    correctAnswer: "人文主義",
    acceptedAnswers: [],
    explanation: "測試用解釋。",
    knowledgePoint: "文藝復興人文主義",
    sourceExcerpt: "測試用教材節錄文字",
    sourceLocation: "測試教材 第 1 段",
    sourceBlockIds: [],
    gradingPoints: [],
    origin: "material-mock",
    status: "draft",
    sourceVerified: true,
    createdAt: new Date().toISOString(),
  });
  questionsRepo.insertQuestion(question);
  return question.id;
}

describe("自動發布邊界（fail-closed）", () => {
  it("偵測環境：本機示範為 false，Cloud Run 及 NODE_ENV=production 為 true", () => {
    expect(config.isProductionRuntime()).toBe(false);

    process.env.K_SERVICE = "history-self-study";
    expect(config.isProductionRuntime()).toBe(true);
    delete process.env.K_SERVICE;

    env.NODE_ENV = "production";
    expect(config.isProductionRuntime()).toBe(true);
    env.NODE_ENV = "test";
    expect(config.isProductionRuntime()).toBe(false);
  });

  it("Cloud Run 環境下一律拒絕自動發布，題目維持草稿", () => {
    process.env.K_SERVICE = "history-self-study";
    const questionId = insertDraft();

    expect(() => questionService.publishAutoGeneratedQuestion(questionId)).toThrowError(
      /正式環境/,
    );
    expect(questionsRepo.getQuestion(questionId)?.status).toBe("draft");
    expect(questionsRepo.listQuestionReviews(questionId)).toEqual([]);
  });

  it("NODE_ENV=production 時同樣拒絕自動發布", () => {
    env.NODE_ENV = "production";
    const questionId = insertDraft();

    expect(() => questionService.publishAutoGeneratedQuestion(questionId)).toThrowError(
      /正式環境/,
    );
    expect(questionsRepo.getQuestion(questionId)?.status).toBe("draft");
  });

  it("示範自動發布關閉時拒絕自動發布", () => {
    process.env.DEMO_AUTO_PUBLISH_QUESTIONS = "false";
    const questionId = insertDraft();

    expect(() => questionService.publishAutoGeneratedQuestion(questionId)).toThrowError(
      /DEMO_AUTO_PUBLISH_QUESTIONS/,
    );
    expect(questionsRepo.getQuestion(questionId)?.status).toBe("draft");
  });

  it("批次生成在正式環境只建立草稿，並回報停用原因", async () => {
    process.env.K_SERVICE = "history-self-study";
    const before = questionsRepo.countQuestions({ statuses: ["published"] });

    const report = await bank.generateQuestionBank({ topicId: "topic-5", perSection: 1 });

    expect(report.autoPublish).toBe(false);
    expect(report.autoPublishSuppressedReason ?? "").toContain("正式環境");
    expect(report.published).toBe(0);
    expect(questionsRepo.countQuestions({ statuses: ["published"] })).toBe(before);
  });

  it("本機示範模式仍可自動發布，但不會留下覆核紀錄", () => {
    const questionId = insertDraft();

    questionService.publishAutoGeneratedQuestion(questionId);

    expect(questionsRepo.getQuestion(questionId)?.status).toBe("published");
    // 沒有覆核紀錄：教師端會標示為「已發布（未經人工覆核）」
    expect(questionsRepo.listQuestionReviews(questionId)).toEqual([]);
    expect(questionService.reviewStateFor(questionsRepo.getQuestion(questionId)!)).toBe(
      "published-unreviewed",
    );
  });
});
