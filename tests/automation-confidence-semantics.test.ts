/**
 * 「自動檢查通過」與「教育／史實認可」必須分開（Sprint 8.5 第五階段）。
 *
 * 這一組測試鎖定三件不可混淆的事：
 *   1. 通過自動品質驗證的題目只會被標示為「機器檢查通過」，教師端看到的是
 *      `published-unreviewed`，資料庫**沒有**任何人工覆核紀錄。
 *   2. 機器動作（重新執行品質驗證）**不會**建立覆核紀錄，亦不能在閘門判定為 `revise`
 *      時釋放題目（見 tests/question-quality-gate.test.ts 的繞過路徑迴歸測試）。
 *   3. 判定結果只包含自動檢查的資訊：沒有「已認可／已核准」一類欄位，
 *      亦不會因為題目存在而假裝已覆核（`golden-questions.v1.json` 必須保持空／待覆核）。
 *
 * 全部使用本地示範生成（`LLM_PROVIDER=mock`）及測試資料庫，不呼叫任何付費 AI。
 */
import fs from "node:fs";
import path from "node:path";
import { beforeAll, describe, expect, it } from "vitest";
import { freshTestDatabasePath } from "./test-database";

process.env.APP_DATABASE_PATH = freshTestDatabasePath("automation-confidence");
process.env.LLM_PROVIDER = "mock";
process.env.AUTO_PUBLISH_VALIDATED_QUESTIONS = "true";
process.env.DEMO_AUTO_PUBLISH_QUESTIONS = "true";
process.env.AUTH_SECRET = "test-secret-0123456789abcdefghijklmnop";
delete process.env.ADMIN_TOKEN;
delete process.env.K_SERVICE;

type QuestionRepo = typeof import("@/server/repositories/questions");
type QuestionService = typeof import("@/server/services/question-service");
type SeedModule = typeof import("@/server/seed");

let questions: QuestionRepo;
let questionService: QuestionService;
let seed: SeedModule;

beforeAll(async () => {
  questions = await import("@/server/repositories/questions");
  questionService = await import("@/server/services/question-service");
  seed = await import("@/server/seed");
  seed.ensureBootstrap();
});

describe("自動檢查通過 ≠ 已獲教育／史實認可", () => {
  it("通過自動驗證的題目在教師端標示為「已發布（未經人工覆核）」且沒有覆核紀錄", () => {
    const question = questions.insertQuestion({
      id: "fx-confidence-demo",
      topicId: "topic-1",
      sectionId: "topic-1-origins",
      questionType: "mc",
      difficulty: "basic",
      question: "合成問題：以下哪一項是合成項目？",
      options: ["合成甲", "合成乙", "合成丙", "合成丁"],
      correctAnswer: "合成甲",
      acceptedAnswers: [],
      explanation: "合成解釋：用於驗證機器發布的標示。",
      knowledgePoint: "合成知識點",
      sourceExcerpt: "合成節錄文字",
      sourceLocation: "合成教材 · 第 1 段",
      sourceBlockIds: [],
      gradingPoints: [],
      origin: "demo",
      status: "draft",
      sourceVerified: false,
      skill: null,
      qualityWarnings: [],
      autoValidatedAt: null,
      autoValidatedRevision: null,
      autoValidatedFingerprint: null,
      teacherConfirmationRequired: false,
      revision: 1,
      createdAt: new Date().toISOString(),
    });

    // 明確由機器路徑發布（示範自動發布，不建立任何覆核紀錄）
    questionService.publishAutoGeneratedQuestion(question.id);
    const view = questionService.teacherQuestionView(questions.getQuestion(question.id)!);
    expect(view.question.status).toBe("published");
    // 教師端必須看得出這是未經人工覆核的發布
    expect(view.reviewState).toBe("published-unreviewed");
    expect(view.approvedReview).toBeNull();
    expect(view.latestReview).toBeNull();
  });

  it("機器重新驗證不會建立任何人工覆核紀錄", () => {
    const question = questions.insertQuestion({
      id: "fx-confidence-1",
      topicId: "topic-1",
      sectionId: "topic-1-origins",
      questionType: "mc",
      difficulty: "basic",
      question: "合成問題：以下哪一項是合成答案？",
      options: ["合成甲", "合成乙", "合成丙", "合成丁"],
      correctAnswer: "合成甲",
      acceptedAnswers: [],
      explanation: "合成解釋：用於驗證機器驗證不會留下人工紀錄。",
      knowledgePoint: "合成知識點",
      sourceExcerpt: "合成節錄文字",
      sourceLocation: "合成教材 · 第 1 段",
      sourceBlockIds: [],
      gradingPoints: [],
      origin: "manual",
      status: "draft",
      sourceVerified: false,
      skill: null,
      qualityWarnings: [],
      autoValidatedAt: null,
      autoValidatedRevision: null,
      autoValidatedFingerprint: null,
      teacherConfirmationRequired: false,
      revision: 1,
      createdAt: new Date().toISOString(),
    });

    questionService.revalidateQuestion(question.id);
    const reviews = questions.listQuestionReviews(question.id);
    expect(reviews).toHaveLength(0);
    const view = questionService.teacherQuestionView(questions.getQuestion(question.id)!);
    expect(view.approvedReview).toBeNull();
  });

  it("閘門判定不會產生任何「已認可」欄位（只有自動檢查的結果）", async () => {
    const { checkQuestionQuality } = await import("@/server/llm/question-quality");
    const result = checkQuestionQuality(
      {
        questionType: "mc",
        question: "以下哪一項是「人文主義」的說明？",
        options: ["強調人的價值與理性，並重視古典學問", "主張君主權力來自神，人民必須服從"],
        correctAnswer: "強調人的價值與理性，並重視古典學問",
        explanation: "教材把人文主義說明為強調人的價值與理性、並重視古典學問的思想，這一項符合這段說明。",
        sourceExcerpt: "人文主義：一種強調人的價值與理性，並重視古典學問的思想。",
        sourceBlockIds: ["x"],
      },
      [
        {
          blockId: "x",
          sourceLocation: "合成教材 · 第 1 段",
          text: "人文主義：一種強調人的價值與理性，並重視古典學問的思想。",
        },
      ],
    );
    // 判定只有 ok／issues／outcome：沒有 confidence、approved 或 expert 之類的欄位
    expect(Object.keys(result).sort()).toEqual(["issues", "ok", "outcome"]);
    for (const issue of result.issues) {
      expect(Object.keys(issue).sort()).toEqual(["code", "message", "severity"]);
      expect(["blocking", "uncertain", "warning"]).toContain(issue.severity);
    }
  });

  it("黃金題庫仍是空的並標示待覆核（不得由程式填入認可）", () => {
    const file = path.join("docs", "teacher-review", "golden-questions.v1.json");
    const golden = JSON.parse(fs.readFileSync(file, "utf8")) as {
      reviewStatus?: string;
      questions?: unknown[];
    };
    expect(golden.reviewStatus).toBe("pending-review");
    expect(golden.questions ?? []).toHaveLength(0);
  });
});
